export function resolveTheme(themeId, overrides, cssVars) {
  const base = THEME_SYSTEMS[themeId]
  if (!base) return null
  return {
    ...base,
    resolved: {
      bg:       overrides && overrides.bg       || cssVars && cssVars['--bg']       || base.bg,
      card:     overrides && overrides.card     || cssVars && cssVars['--card']     || base.card,
      headline: overrides && overrides.headline || cssVars && cssVars['--headline'] || base.headline,
      button:   overrides && overrides.button   || cssVars && cssVars['--button']   || base.button,
      text:     overrides && overrides.text     || cssVars && cssVars['--text']     || base.text,
      headingFont: overrides && overrides.headingFont || cssVars && cssVars['--font-heading'] || base.headingFont,
      bodyFont:    overrides && overrides.bodyFont    || cssVars && cssVars['--font-body']    || base.bodyFont,
    },
  }
}

export function exportThemeJSON(config) {
  const resolved = resolveTheme(config.themeId, config.overrides, config.cssVars)
  const payload = {
    version: '1.0',
    exportedAt: new Date().toISOString(),
    theme: {
      id: config.themeId,
      name: resolved && resolved.name,
      category: config.category,
      colors: resolved && resolved.resolved,
      fonts: {
        heading: resolved && resolved.resolved && resolved.resolved.headingFont,
        body: resolved && resolved.resolved && resolved.resolved.bodyFont,
      },
      accessibility: {
        highContrast: config.highContrast,
        reduceMotion: config.reduceMotion,
      },
      layout: {
        fontSizeScale: config.fontSizeScale,
        borderRadius: config.borderRadius,
      },
      overrides: config.overrides,
      cssVars: config.cssVars,
    },
  }
  return JSON.stringify(payload, null, 2)
}

const I18nContext = createContext(null)

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => localStorage.getItem('mg_lang') || 'en')
  const changeLang = useCallback((l) => {
    setLang(l)
    try { localStorage.setItem('mg_lang', l) } catch (e) { /* ignore */ }
  }, [])
  const t = useCallback((key) => dict[lang]?.[key] ?? dict.en[key] ?? key, [lang])
  const value = useMemo(() => ({ lang, setLang: changeLang, t }), [lang, changeLang, t])
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useI18n() {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n must be used within I18nProvider')
  return ctx
}
